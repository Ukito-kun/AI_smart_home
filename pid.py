import os
import shutil
import sys
import threading
import time

# ==========================================
# БЛОК 1: Кроссплатформенная настройка ввода
# ==========================================
# Определяем, какая операционная система задействована,
# чтобы выбрать правильные модули для посимвольного чтения клавиатуры.
IS_WINDOWS = os.name == "nt"

if IS_WINDOWS:
  import msvcrt  # Встроенный модуль Windows для работы с консолью и клавишами

  # Важная строчка для Windows: заставляет системную консоль
  # (CMD / PowerShell) понимать стандартные ANSI-escape-последовательности.
  os.system("")
else:
  import termios  # Модуль Linux/macOS для управления настройками терминала
  import tty  # Модуль для перевода терминала в сырой (raw) режим ввода


def get_key():
  """Считывает ОДНО нажатие клавиши с клавиатуры в реальном времени.

  Работает без ожидания нажатия клавиши Enter (неблокирующий ввод посимвольно).
  Кроссплатформенно: использует msvcrt на Windows и termios/tty на Linux/macOS.
  """
  if IS_WINDOWS:
    ch = msvcrt.getwch()  # Считываем символ на Windows (поддерживает Unicode)
    if ch in (
        "\x00",
        "\xe0",
    ):  # Служебные клавиши (стрелки, F-клавиши и т.д.) шлют два кода
      msvcrt.getwch()  #правляющий байт
      return ""
    return ch
  else:
    # Для Linux/macOS нужно перевести дескриптор ввода в «сырой» режим,
    # чтобы терминал не ждал Enter и не выводил вводимые символы на экран автоматически.
    fd = sys.stdin.fileno()
    old_settings = termios.tcgetattr(fd)
    try:
      tty.setraw(fd)
      ch = sys.stdin.read(1)  # Читаем ровно 1 символ
    finally:
      # Обязательно возвращаем настройки терминала в исходное состояние при выходе
      termios.tcsetattr(fd, termios.TCSADRAIN, old_settings)
    return ch


# ==========================================
# БЛОК 2: Глобальные переменные и защита потоков
# ==========================================

# screen_lock — это мьютекс (Lock).
# Поскольку у нас работают два потока одновременно (фоновый симулятор и главный поток ввода),
# они оба пишут в консоль. Мьютекс гарантирует, что они не «перебьют» друг друга
# и текст на экране не смешается в кашу.
screen_lock = threading.Lock()

input_buffer = []  # Список символов, которые пользователь уже напечатал, но еще не отправил (Enter)
prompt_prefix = ">> "  # Приглашение ввода внизу экрана
simulation_running = (
    True  # Флаг для безопасной остановки фонового потока симулятора
)


def get_term_size():
  """Возвращает текущую высоту (rows) и ширину (cols) окна терминала.

  Используется библиотека shutil, размеры подстраиваются даже если пользователь
  растягивает окно мышкой прямо во время работы программы.
  """
  cols, rows = shutil.get_terminal_size((80, 24))
  return rows, cols


# ==========================================
# БЛОК 3: Управление графикой терминала (ANSI)
# ==========================================


def redraw_prompt():
  """Перерисовывает строку ввода строго на самой нижней строке экрана.

  Использует ANSI-коды положения курсора и очистки строки.
  """
  rows, cols = get_term_size()
  current_text = "".join(input_buffer)

  # Склеиваем префикс и набранный текст.
  # Обрезаем по ширине экрана (cols - 1), чтобы текст не ломал верстку при переполнении строки.
  display_text = (prompt_prefix + current_text)[: cols - 1]

  # \033[{rows};1H — переместить курсор на последнюю строку, 1-й столбец.
  # \033[2K         — полностью очистить эту строку от старого текста.
  # Выводим актуальный текст ввода.
  sys.stdout.write(f"\033[{rows};1H\033[2K{display_text}")
  sys.stdout.flush()


def print_log(message: str):
  """Выводит фоновое сообщение (лог) в верхнюю область экрана,

  НЕ стирая и НЕ смещая строку ввода пользователя внизу.
  """
  with screen_lock:  # Блокируем доступ, чтобы вывод был атомарным
    rows, cols = get_term_size()

    # Магия ANSI-последовательностей для разделения экрана:
    # 1. \033[s           — сохраняем текущую позицию курсора.
    # 2. \033[{rows-1};1H — прыгаем на предпоследнюю строку терминала.
    # 3. \n               — печатаем сообщение. Благодаря настроенной области прокрутки (scroll region),
    #                       текст вверху сдвинется вверх, а нижняя строка останется на месте!
    sys.stdout.write(f"\033[s\033[{rows-1};1H\n{message}")

    # 4. \033[u           — возвращаем курсор обратно на сохраненную позицию.
    sys.stdout.write("\033[u")

    # 5. Обязательно перерисовываем строку ввода внизу, чтобы зафиксировать курсор на месте.
    redraw_prompt()


# ==========================================
# БЛОК 4: Фоновый процесс (Симуляция дома)
# ==========================================


def background_simulation():
  """Фоновый поток, который имитирует работу умного дома.

  Живет своей жизнью и отправляет сообщения через print_log.
  """
  global simulation_running
  step = 1
  while simulation_running:
    time.sleep(3)  # Имитация паузы между событиями (например, раз в 3 секунды)
    print_log(
        f"[СИМУЛЯЦИЯ] Шаг {step}: Проверка датчиков... Температура стабильна."
    )
    step += 1


# ==========================================
# БЛОК 5: Главная функция и цикл обработки ввода
# ==========================================


def main():
  global simulation_running, input_buffer

  rows, cols = get_term_size()

  # НАСТРОЙКА ОБЛАСТИ ПРОКРУТКИ (Scroll Region):
  # \033[1;{rows-1}r говорит терминалу: «Скроллить и поднимать текст разрешено
  # ТОЛЬКО в диапазоне от 1-й до предпоследней строки (rows-1). Последнюю строку не трогай!»
  sys.stdout.write(f"\033[1;{rows-1}r")

  # \033[2J — полностью очищаем экран терминала перед стартом.
  sys.stdout.write("\033[2J")
  sys.stdout.flush()

  # Приветственные логи
  print_log("=== Симулятор Умного Дома запущен ===")
  print_log(
      "Печатайте команды внизу. Логи выводятся выше, не мешая вводу.\n"
  )

  # Создаем и запускаем фоновый поток симуляции (daemon=True означает,
  # что поток автоматически закроется при выходе из программы)
  sim_thread = threading.Thread(target=background_simulation, daemon=True)
  sim_thread.start()

  # Рисуем пустую строку ввода в первый раз
  with screen_lock:
    redraw_prompt()

  try:
    # Главный цикл программы: постоянно слушает клавиатуру
    while True:
      key = get_key()  # Читаем нажатую клавишу в реальном времени

      if not key:
        continue

      # --- ОБРАБОТКА ENTER (отправка команды) ---
      if key in ("\r", "\n"):
        command = "".join(input_buffer).strip()
        input_buffer.clear()  # Очищаем буфер набранного текста

        with screen_lock:
          redraw_prompt()

        if command:
          print_log(f"[Пользователь]: {command}")

          # Обработка команд пользователя
          if command.lower() == "exit":
            print_log("Завершение работы системы...")
            simulation_running = False
            break
          elif command.lower() == "help":
            print_log("Доступные команды: help, status, exit")
          elif command.lower() == "status":
            print_log("Статус: Все системы работают в штатном режиме.")
          else:
            print_log(f"Неизвестная команда: '{command}'")

      # --- ОБРАБОТКА BACKSPACE (удаление символа) ---
      elif key in ("\x08", "\x7f"):
        if input_buffer:
          input_buffer.pop()  # последний символ из памяти
          with screen_lock:
            redraw_prompt()  # Перерисовываем экран

      # --- ОБРАБОТКА CTRL+C (экстренный выход) ---
      elif key == "\x03":
        break

      # --- ОБРАБОТКА ОБЫЧНЫХ СИМВОЛОВ ---
      elif ord(key) >= 32:  # Проверяем, что символ печатный
        input_buffer.append(key)  # Добавляем символ в буфер
        with screen_lock:
          redraw_prompt()  # Сразу отображаем его на экране

  finally:
    # СБРОС НАСТРОЕК ТЕРМИНАЛА ПРИ ВЫХОДЕ:
    # Обязательно возвращаем стандартную область прокрутки (\033[r),
    # иначе после закрытия программы терминал пользователя останется «сломанным».
    sys.stdout.write("\033[r")
    sys.stdout.write("\nСимуляция полностью остановлена.\n")
    sys.stdout.flush()


if __name__ == "__main__":
  main()
